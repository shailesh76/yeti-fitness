-- Fail loudly if the embedded manifest is not the expected size.
DO $$
DECLARE v_n pg_catalog.int4;
BEGIN
  SELECT pg_catalog.count(*) INTO v_n FROM _yeti_canonical;
  IF v_n <> 396 THEN
    RAISE EXCEPTION 'Manifest size % does not match expected 396', v_n;
  END IF;
