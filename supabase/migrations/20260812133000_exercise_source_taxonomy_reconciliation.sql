-- ---------------------------------------------------------------------------
-- 2. Pre-flight: every canonical slug must exist exactly once live.
--    If the catalogue has drifted, stop rather than mislabel anything.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  v_missing pg_catalog.int4;
  v_dupes   pg_catalog.int4;
BEGIN
  SELECT pg_catalog.count(*) INTO v_missing
  FROM _yeti_canonical c
  WHERE NOT EXISTS (SELECT 1 FROM public.exercises e WHERE e.slug = c.slug);

  SELECT pg_catalog.count(*) INTO v_dupes
  FROM (
    SELECT e.slug FROM public.exercises e
    JOIN _yeti_canonical c ON c.slug = e.slug
    GROUP BY e.slug HAVING pg_catalog.count(*) > 1
  ) d;

  IF v_missing > 0 THEN
    RAISE EXCEPTION 'Aborting: % canonical slug(s) absent from public.exercises', v_missing;
  END IF;
  IF v_dupes > 0 THEN
    RAISE EXCEPTION 'Aborting: % canonical slug(s) duplicated in public.exercises', v_dupes;
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 3. Classify. Manifest membership wins; coach authorship is the only other
--    positive signal; everything else is legacy. Ids are never touched.
-- ---------------------------------------------------------------------------

-- 3a. Manifest-proven Yeti rows.
UPDATE public.exercises e
SET source_type = 'yeti_first_party'
FROM _yeti_canonical c
WHERE e.slug = c.slug
  AND e.created_by_coach_id IS NULL
  AND e.source_type IS DISTINCT FROM 'yeti_first_party';

-- 3b. Coach-authored rows are custom, whatever their inherited source_type
--     says. Checked after 3a so a coach copy of a catalogue slug stays custom.
UPDATE public.exercises
SET source_type = 'custom'
WHERE created_by_coach_id IS NOT NULL
  AND source_type IS DISTINCT FROM 'custom';

-- 3c. Everything else is legacy catalogue. This is the branch that repairs
--     rows which merely inherited the 'yeti_v2' DEFAULT.
UPDATE public.exercises e
SET source_type = 'legacy_catalog'
WHERE e.created_by_coach_id IS NULL
  AND NOT EXISTS (SELECT 1 FROM _yeti_canonical c WHERE c.slug = e.slug)
  AND e.source_type IS DISTINCT FROM 'legacy_catalog';

-- ---------------------------------------------------------------------------
-- 4. Dataset provenance into metadata, from explicit membership only.
--    Stored as a JSON array so a shared slug records ["v2","v3"].
-- ---------------------------------------------------------------------------
UPDATE public.exercises e
SET metadata = COALESCE(e.metadata, '{}'::jsonb)
             || jsonb_build_object(
                  'dataset_version',
                  (SELECT jsonb_agg(v ORDER BY v)
                   FROM pg_catalog.unnest(pg_catalog.string_to_array(c.dataset_versions, ',')) AS v),
                  -- Which dataset owns the content, so a later re-import is
                  -- deterministic rather than order-dependent.
                  'content_source', pg_catalog.to_jsonb(c.merge_winner)
                )
FROM _yeti_canonical c
WHERE e.slug = c.slug;

-- Legacy/custom rows must not carry a Yeti dataset_version claim.
UPDATE public.exercises e
SET metadata = e.metadata - 'dataset_version' - 'content_source'
WHERE e.source_type <> 'yeti_first_party'
  AND e.metadata ? 'dataset_version';

-- ---------------------------------------------------------------------------
-- 5. Stop the contamination at source: the DEFAULT is what let unrelated rows
--    inherit Yeti provenance in the first place.
-- ---------------------------------------------------------------------------
ALTER TABLE public.exercises ALTER COLUMN source_type SET DEFAULT 'legacy_catalog';

-- ---------------------------------------------------------------------------
-- 6. Constrain the vocabulary — but only after proving nothing falls outside
--    it, so the migration reports the offending values instead of a bare
--    constraint violation.
-- ---------------------------------------------------------------------------
DO $$
DECLARE v_bad pg_catalog.text;
BEGIN
  SELECT pg_catalog.string_agg(DISTINCT COALESCE(source_type, '<NULL>'), ', ')
  INTO v_bad
  FROM public.exercises
  WHERE source_type IS NULL
     OR source_type NOT IN ('yeti_first_party', 'legacy_catalog', 'custom');

  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'Aborting: unclassified source_type value(s) remain: %', v_bad;
  END IF;
END $$;

ALTER TABLE public.exercises DROP CONSTRAINT IF EXISTS exercises_source_type_check;
ALTER TABLE public.exercises
  ADD CONSTRAINT exercises_source_type_check
  CHECK (source_type IN ('yeti_first_party', 'legacy_catalog', 'custom'));

COMMIT;
