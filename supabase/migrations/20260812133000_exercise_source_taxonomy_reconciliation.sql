-- ============================================================================
-- 20260812133000_exercise_source_taxonomy_reconciliation.sql
-- ============================================================================
-- Reconciles public.exercises.source_type onto the canonical taxonomy:
--
--     yeti_first_party  Yeti-owned catalogue (V2 + V3 datasets)
--     legacy_catalog    externally sourced rows imported before the Yeti library
--     custom            coach-authored exercises
--
-- WHY THIS IS NOT A BLANKET UPDATE
--
-- The obvious "UPDATE ... SET source_type='yeti_first_party' WHERE
-- source_type='yeti_v2'" is unsafe: exercises.source_type carries
-- DEFAULT 'yeti_v2', so ANY row ever inserted without an explicit source_type
-- silently looks Yeti-owned. Existing source_type values are therefore treated
-- here as untrusted, and membership comes only from the checked-in datasets via
-- the manifest below (generated by scripts/generate_exercise_provenance.ts).
--
-- Dataset version is likewise NOT inferred from ID shape. V2 dataset ids are
-- not UUIDs ("yeti-ex-0001"), so the importer minted UUIDs for them: 365 live
-- rows carry the 00000000-0000-4000-a000-* shape while the V3 dataset holds
-- only 200 records. ID prefix proves nothing.
--
-- The manifest is keyed by slug, which is unique within each dataset and
-- already matches the live catalogue 1:1. Row ids are never rewritten, so
-- plan_exercises / session_sets / exercise history references stay intact.
--
-- Idempotent. No deletes. Aborts rather than guessing.
-- ============================================================================

BEGIN;

