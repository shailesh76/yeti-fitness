-- ============================================================================
-- 20260812140000_exercise_default_reps_lossless.sql
-- ============================================================================
-- PROPOSED — NOT YET APPLIED.
--
-- Makes exercises.default_reps lossless.
--
-- THE PROBLEM
--
-- default_reps is integer. Every one of the 420 authored prescriptions is a
-- STRING: "8–12", "30–60 sec", "30–60 seconds", "6–10 controlled reps"
-- (note the EN DASH, U+2013). The importer reduced each to its first integer
-- via /d+/, so live rows now read:
--
--     default_reps = 8   x357   (from "8–12")
--     default_reps = 30  x27    (from "30–60 sec")
--     default_reps = 6   x12    (from "6–10 controlled reps")
--
-- That is not a rounding loss, it is a change of meaning: Sled Push and
-- Air Bike Sprint now prescribe "30 reps" where the author wrote a
-- 30-60 SECOND effort.
--
-- THE CHOICE
--
-- TEXT, not default_reps_min/max. No code performs arithmetic on this column —
-- every consumer only displays it (coach-dashboard exercises page, the
-- WatermelonDB model, ExerciseRepository passthrough). Min/max cannot express
-- "30–60 sec" (a duration, not a count) or "AMRAP" without a second unit
-- column, and the sibling prescription columns hypertrophy_reps /
-- strength_reps / endurance_reps are ALREADY text.
--
-- DEPENDENCY — DO NOT APPLY IN ISOLATION
--
-- packages/database/src/schema.ts types default_reps as a WatermelonDB
-- 'number'. Applying this before the mobile schema migration would break
-- sync-pull decoding on existing installs. That mobile migration is Round 2
-- work and is deliberately still deferred.
-- ============================================================================

